#!/usr/bin/env node

import { access, mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";

const GENERATED_MARKER = "<!-- Generated by scripts/generate-previews.js. Do not edit manually. -->";
const ROOT = process.cwd();
const PREVIEW_ROOT = path.join(ROOT, "src/routes/preview");

const themes = {
	blocks: { registry: "registry.json", sourceDirectory: "blocks", previewPrefix: "", fullSlug: false },
	mist: { registry: "mist-registry.json", sourceDirectory: "mist", previewPrefix: "mist", fullSlug: false },
	veil: { registry: "veil-registry.json", sourceDirectory: "veil", previewPrefix: "veil", fullSlug: true },
	dusk: { registry: "dusk-registry.json", sourceDirectory: "dusk", previewPrefix: "dusk", fullSlug: false },
};

function printHelp() {
	console.log(`Generate preview routes from a component registry.

Usage:
  pnpm generate:previews --theme <theme> [options]

Options:
  --theme <name>       blocks, mist, veil, or dusk (required)
  --category <name>    Generate one category only
  --component <name>   Generate one registry component only, e.g. hero-one
  --dry-run            Print changes without writing files
  --check              Exit with code 1 when generated files are missing or stale
  --force              Overwrite handwritten preview pages
  --help                Show this help
`);
}

function parseArgs(argv) {
	const options = {
		theme: undefined,
		category: undefined,
		component: undefined,
		dryRun: false,
		check: false,
		force: false,
		help: false,
	};
	const valueOptions = new Map([
		["--theme", "theme"],
		["--category", "category"],
		["--component", "component"],
	]);
	const booleanOptions = new Map([
		["--dry-run", "dryRun"],
		["--check", "check"],
		["--force", "force"],
		["--help", "help"],
		["-h", "help"],
	]);

	for (let index = 0; index < argv.length; index += 1) {
		const argument = argv[index];
		const [flag, inlineValue] = argument.split("=", 2);

		if (valueOptions.has(flag)) {
			const value = inlineValue ?? argv[++index];
			if (!value || value.startsWith("--")) {
				throw new Error(`${flag} requires a value`);
			}
			options[valueOptions.get(flag)] = value;
			continue;
		}

		if (booleanOptions.has(argument)) {
			options[booleanOptions.get(argument)] = true;
			continue;
		}

		throw new Error(`Unknown argument: ${argument}`);
	}

	if (options.dryRun && options.check) {
		throw new Error("Use either --dry-run or --check, not both");
	}

	return options;
}

function normalizeCategory(theme, directory) {
	if (theme === "mist" && directory.startsWith("m")) {
		return directory.slice(1);
	}

	if (theme === "blocks") {
		return { features: "feature", "logo-cloud": "logocloud" }[directory] ?? directory;
	}

	return directory;
}

function getComponentInfo(theme, item) {
	const themeConfig = themes[theme];
	const sourcePrefix = `src/lib/components/${themeConfig.sourceDirectory}/`;
	const componentFiles = (item.files ?? [])
		.map((file) => (typeof file === "string" ? file : file.path))
		.filter((file) => file?.startsWith(sourcePrefix) && file.endsWith(".svelte"));

	if (componentFiles.length === 0) {
		return null;
	}

	const relativeParts = componentFiles[0].slice(sourcePrefix.length).split("/");
	const sourceCategory = relativeParts[0];
	const category = normalizeCategory(theme, sourceCategory);
	const slugPrefix = `${category}-`;
	const shortSlug = item.name.startsWith(slugPrefix) ? item.name.slice(slugPrefix.length) : item.name;
	const slug = themeConfig.fullSlug ? item.name : shortSlug;
	const preferredBasenames = [`${item.name}.svelte`, `${category}.svelte`, `${slug}.svelte`];
	const entry = preferredBasenames
		.map((basename) => componentFiles.find((file) => path.posix.basename(file) === basename))
		.find(Boolean);

	if (!entry) {
		return null;
	}

	return { category, slug, entry };
}

function createPage(entry) {
	const importPath = entry.replace(/^src\/lib\//, "#lib/");

	return `${GENERATED_MARKER}
<script lang="ts">
	import PreviewComponent from "${importPath}";
</script>

<PreviewComponent />
`;
}

async function fileExists(filePath) {
	try {
		await access(filePath);
		return true;
	} catch {
		return false;
	}
}

async function main() {
	const options = parseArgs(process.argv.slice(2));

	if (options.help) {
		printHelp();
		return;
	}

	if (!options.theme) {
		throw new Error("--theme is required");
	}

	if (!themes[options.theme]) {
		throw new Error(`Unknown theme: ${options.theme}. Expected one of: ${Object.keys(themes).join(", ")}`);
	}

	const registryPath = path.join(ROOT, themes[options.theme].registry);
	const registry = JSON.parse(await readFile(registryPath, "utf8"));
	const candidates = registry.items
		.filter((item) => item.type === "registry:block")
		.map((item) => ({ item, info: getComponentInfo(options.theme, item) }))
		.filter(({ item, info }) => {
			if (options.component && item.name !== options.component) return false;
			if (options.category && info?.category !== options.category) return false;
			return true;
		});

	if (candidates.length === 0) {
		throw new Error("No matching registry blocks found");
	}

	const summary = { created: 0, updated: 0, unchanged: 0, skipped: 0, missingEntry: 0 };
	let hasChanges = false;

	for (const { item, info } of candidates) {
		if (!info) {
			console.warn(`missing entry  ${item.name}`);
			summary.missingEntry += 1;
			continue;
		}

		const routePath = path.join(
			PREVIEW_ROOT,
			themes[options.theme].previewPrefix,
			info.category,
			info.slug,
			"+page.svelte"
		);
		const relativeRoutePath = path.relative(ROOT, routePath);
		const expected = createPage(info.entry);
		const exists = await fileExists(routePath);
		const current = exists ? await readFile(routePath, "utf8") : null;

		if (current === expected) {
			summary.unchanged += 1;
			continue;
		}

		if (exists && !current.includes(GENERATED_MARKER) && !options.force) {
			console.log(`skipped        ${relativeRoutePath} (handwritten; use --force to replace)`);
			summary.skipped += 1;
			continue;
		}

		hasChanges = true;
		const action = exists ? "updated" : "created";
		const label = options.dryRun || options.check ? (exists ? "would update" : "would create") : action;
		console.log(`${label.padEnd(13)} ${relativeRoutePath}`);
		summary[action] += 1;

		if (!options.dryRun && !options.check) {
			await mkdir(path.dirname(routePath), { recursive: true });
			await writeFile(routePath, expected, "utf8");
		}
	}

	console.log(
		`\ncreated ${summary.created}, updated ${summary.updated}, unchanged ${summary.unchanged}, skipped ${summary.skipped}, missing entry ${summary.missingEntry}`
	);

	if (options.check && (hasChanges || summary.missingEntry > 0)) {
		process.exitCode = 1;
	}
}

main().catch((error) => {
	console.error(`Error: ${error.message}`);
	process.exitCode = 1;
});
